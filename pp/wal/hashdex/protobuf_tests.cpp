[[nodiscard]] BareBones::Vector<HistogramSpan> standard_spans() {
  return BareBones::Vector{
      HistogramSpan{.offset = 0, .length = 2},
      HistogramSpan{.offset = 1, .length = 2},
  };
}

[[nodiscard]] BareBones::Vector<HistogramBucketValue> int_buckets(int i) {
  return BareBones::Vector<HistogramBucketValue>{
      {.value = int64_t{i + 1}},
      {.value = 1},
      {.value = -1},
      {.value = 0},
  };
}

[[nodiscard]] BareBones::Vector<HistogramBucketValue> float_buckets(int i) {
  return BareBones::Vector<HistogramBucketValue>{
      {.float_value = static_cast<double>(i + 1)},
      {.float_value = static_cast<double>(i + 2)},
      {.float_value = static_cast<double>(i + 1)},
      {.float_value = static_cast<double>(i + 1)},
  };
}

[[nodiscard]] Timestamp histogram_timestamp(int64_t i) {
  return kStartTimestamp + (kStep * i);
}

[[nodiscard]] Histogram make_int_histogram(int i, Timestamp timestamp, CounterResetHint hint = CounterResetHint::kUnknown) {
  return {
      .timestamp = timestamp,
      .zero_threshold = 0.001,
      .zero_count = {.value = static_cast<uint64_t>(2 + i)},
      .count = {.value = static_cast<uint64_t>(12 + i * 9)},
      .sum = 18.4 * static_cast<double>(i + 1),
      .positive_spans = standard_spans(),
      .negative_spans = standard_spans(),
      .positive_buckets = int_buckets(i),
      .negative_buckets = int_buckets(i),
      .type = HistogramType::kInt,
      .schema = 1,
      .counter_reset_hint = hint,
  };
}

